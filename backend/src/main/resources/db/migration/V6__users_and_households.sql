-- Usuarios. "user" es palabra reservada en PostgreSQL, por eso app_user.
CREATE TABLE app_user (
                          id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          email         VARCHAR(254) NOT NULL,
                          password_hash VARCHAR(100) NOT NULL,
                          display_name  VARCHAR(80)  NOT NULL,
                          created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_app_user_email_ci ON app_user (lower(email));

CREATE TABLE household (
                           id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name       VARCHAR(80) NOT NULL,
                           created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Membresía: un usuario puede estar en varios hogares, con un rol en cada uno.
CREATE TABLE household_member (
                                  household_id BIGINT      NOT NULL REFERENCES household (id) ON DELETE CASCADE,
                                  user_id      BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
                                  role         VARCHAR(10) NOT NULL CHECK (role IN ('OWNER', 'EDITOR', 'VIEWER')),
                                  joined_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
                                  PRIMARY KEY (household_id, user_id)
);
CREATE INDEX idx_household_member_user ON household_member (user_id);

